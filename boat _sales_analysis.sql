-- **47.find pairs of different products belonging to the same product category where one product has a higher price than the other.
--Display both product names, their prices, and the category. Avoid duplicate pairs.
SELECT
    p1.productname AS product1,
    p1.costprice AS price1,
    p2.productname AS product2,
    p2.costprice AS price2,
    p1.category
FROM products p1
JOIN products p2
    ON p1.category = p2.category
    AND p1.productid < p2.productid
WHERE p1.costprice <> p2.costprice
ORDER BY p1.category;

