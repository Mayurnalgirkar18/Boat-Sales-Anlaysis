-- q6. find the top three customers based on total revenue

with customer_sales as (
    select
        customerid,
        sum(netsales) as total_revenue
    from sales
    group by customerid
),
ranked_customers as (
    select
        customerid,
        total_revenue,
        dense_rank() over(
            order by total_revenue desc
        ) as customer_rank
    from customer_sales
)
select *
from ranked_customers
where customer_rank <= 3
order by customer_rank;


