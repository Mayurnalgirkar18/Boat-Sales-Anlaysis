-- q10. calculate each product's percentage contribution to total company revenue

select
    productid,
    sum(netsales) as product_revenue,
    round(
        sum(netsales) * 100.0 /
        nullif(sum(sum(netsales)) over(), 0),
        2
    ) as revenue_contribution_pct
from sales
group by productid
order by product_revenue desc;


