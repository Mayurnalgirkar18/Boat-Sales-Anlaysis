-- q1. rank customers based on their total revenue

select
    customerid,
    sum(netsales) as total_revenue,
    rank() over(order by sum(netsales) desc) as customer_rank
from sales
group by customerid
order by customer_rank;


-- q2. assign a row number to each customer's orders from oldest to newest

select
    customerid,
    salesid,
    orderdate,
    netsales,
    row_number() over(
        partition by customerid
        order by orderdate
    ) as order_number
from sales;


-- q3. find the latest order for each customer using row_number

with ranked_orders as (
    select
        customerid,
        salesid,
        orderdate,
        netsales,
        row_number() over(
            partition by customerid
            order by orderdate desc
        ) as row_num
    from sales
)
select *
from ranked_orders
where row_num = 1;


-- q4. calculate running total of company revenue

select
    orderdate,
    salesid,
    netsales,
    sum(netsales) over(
        order by orderdate, salesid
    ) as running_revenue
from sales
order by orderdate, salesid;


