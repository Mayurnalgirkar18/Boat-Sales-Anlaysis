-- q17. find the top 3 products based on total profit
-- within every product category.
-- calculate total profit for each product.
-- rank products within each category using dense_rank().
-- display only the top 3 products in each category.

with cte as (
select productid,productcategory,
sum(profit) as total_profit
from sales
group by productid, productcategory
),
ranke as (
select *, dense_rank() over(partition by productcategory
order by total_profit desc) as rankk
from cte
)
select * from ranke
where rankk <= 3
order by productcategory,  rankk;


